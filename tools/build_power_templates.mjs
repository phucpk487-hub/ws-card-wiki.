// Builds js/import/powerTemplates.js from labelled card bands (test/fixtures/power-bands.json).
// Each fixture entry is a card whose power was verified; its glyphs become the digit templates.
// Usage: node tools/build_power_templates.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { extractGlyphs, classify, GW, GH } from '../js/import/power.js';

const fx = JSON.parse(readFileSync(new URL('../test/fixtures/power-bands.json', import.meta.url)));
const samples = [];
for (const c of fx) {
  const g = extractGlyphs(Uint8Array.from(c.gray), c.bw, c.bh, c.w), s = String(c.power);
  if (g.length !== s.length) throw new Error(`${c.number}: found ${g.length} glyphs for ${s}`);
  g.forEach((glyph, i) => samples.push({ digit: s[i], glyph, card: c.number }));
}
const mean = (list) => { const o = new Float32Array(GW * GH); for (const g of list) g.forEach((v, i) => { o[i] += v / list.length; }); return o; };
const build = (items) => { const by = {}; for (const s of items) (by[s.digit] ||= []).push(s.glyph); return Object.fromEntries(Object.entries(by).map(([d, l]) => [d, mean(l)])); };

// leave-one-card-out check, and the distance spread of correct matches
let wrong = 0, maxOk = 0, loo = 0;
for (const c of fx) {
  const t = build(samples.filter((s) => s.card !== c.number));
  for (const s of samples.filter((x) => x.card === c.number)) {
    if (!(s.digit in t)) continue; // only one card had this digit
    loo++; const r = classify(s.glyph, t);
    if (r.digit !== s.digit) wrong++; else maxOk = Math.max(maxOk, r.d);
  }
}
console.log(`leave-one-card-out: ${wrong} wrong of ${loo}; worst correct distance ${maxOk.toFixed(4)}`);
const T = build(samples), out = {};
for (const [d, t] of Object.entries(T)) out[d] = Array.from(t, (v) => Math.round(v * 100) / 100);
const counts = Object.fromEntries(Object.entries(T).map(([d]) => [d, samples.filter((s) => s.digit === d).length]));
console.log('digits:', counts);
writeFileSync(new URL('../js/import/powerTemplates.js', import.meta.url),
  `// Generated by tools/build_power_templates.mjs from verified card bands. Do not edit by hand.\n// Digits without an entry (here: 3) are learned from corrections made on the import review screen.\nexport const POWER_TEMPLATES = ${JSON.stringify(out)};\n`);
