def descriptor(rgb, cx, cy, hexw, shift=(0, 0)):
    """rgb: HxWx3 uint8. Returns (grid GRIDxGRID float list, hue, fraction) or None when no glyph."""
    half = int(round(.31 * hexw))
    x0, y0 = int(round(cx + shift[0])) - half, int(round(cy + shift[1])) - half
    x0, y0 = max(0, x0), max(0, y0)
    win = rgb[y0:y0 + 2 * half, x0:x0 + 2 * half].astype(float) / 255
    if win.size == 0: return None
    mx, mn = win.max(2), win.min(2)
    sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1e-9), 0)
    mask = (sat > .28) & (mx > .3)
    frac = mask.mean()
    if frac < .06: return {'frac': frac}
    ys, xs = np.where(mask)
    y1, y2, x1, x2 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    sub = mask[y1:y2, x1:x2].astype(float)
    im = Image.fromarray((sub * 255).astype('uint8')).resize((GRID, GRID), Image.BOX)
    g = np.asarray(im).astype(float) / 255
    px = win[mask]
    hs = [colorsys.rgb_to_hsv(*p)[0] for p in px]
    ang = np.array(hs) * 2 * np.pi
    hue = (np.degrees(np.arctan2(np.sin(ang).mean(), np.cos(ang).mean())) % 360)
    return {'frac': frac, 'grid': g, 'hue': hue, 'aspect': (x2 - x1) / (y2 - y1)}

def distance(d, t):
    dh = abs(d['hue'] - t['hue']); dh = min(dh, 360 - dh) / 180
    return float(np.abs(d['grid'] - t['grid']).mean() * 2 + dh * .6)

