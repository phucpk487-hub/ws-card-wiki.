"""Build js/import/triggerTemplates.js from sample card images.
Usage: python3 tools/trigger_templates.py        (run from the project root; sample paths/centres are listed in SAMPLES below)
Each sample is a card (or the trigger chart) image + the centre and width in pixels of one trigger hexagon.
The glyph is the saturated part of the hexagon's inside, cropped to its bounding box and averaged to GRID x GRID."""
