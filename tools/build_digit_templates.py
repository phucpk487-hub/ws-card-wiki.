#!/usr/bin/env python3
"""
Build js/data/digit-templates.js (used by the in-app importer to read the power box)
from converted cards whose power values you have verified.

  python3 tools/build_digit_templates.py <your pack>/cards.json

Only cards with a main image and a numeric power are used, so run it after checking
overrides.json. It also writes test/fixtures/power-crops.json for the unit tests.
The geometry below must match js/lib/card-image.js.
"""
import base64, json, os, sys
import numpy as np
from PIL import Image

W0, H0, PITCH, CW, CH = 140, 80, 17.2, 10, 16
KEEP_PER_DIGIT = 14


def crop_gray(path):
    im = Image.open(path).convert('L'); w, h = im.size
    return np.array(im.crop((0, int(.88 * h), int(.3 * w), h)).resize((W0, H0), Image.BOX), dtype=float)


def cells(g, shift=0):
    z = g[24:48, 36:124] > 170
    cols = np.where(z.sum(0) >= 6)[0]
    xs, xe = cols.min() + 36, cols.max() + 36
    n = max(1, round((xe - xs + 1) / PITCH)); cx = (xs + xe) / 2 + shift; out = []
    for i in range(n):
        c = cx + (i - (n - 1) / 2) * PITCH
        a, b = int(round(c - PITCH / 2)), int(round(c + PITCH / 2))
        patch = g[22:50, max(a, 0):b]
        im = Image.fromarray(np.clip(patch, 0, 255).astype('uint8')).resize((CW, CH), Image.BOX)
        out.append(np.array(im, dtype=float).flatten() / 255)
    return out


def main():
    pack = json.load(open(sys.argv[1]))
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    chars = [c for c in pack['cards'] if c['type'] == 'Character' and c.get('image') and c.get('power')]
    samples = {}
    crops = {}
    for c in chars:
        g = crop_gray(os.path.join(root, c['image']))
        crops[c['number']] = (g, c['power'])
        s = str(c['power'])
        for sh in (-1, 0, 1):
            cs = cells(g, sh)
            if len(cs) != len(s):
                print('skip', c['number'], 'digit count mismatch'); break
            for i, ch in enumerate(s):
                samples.setdefault(ch, []).append(cs[i])
    # keep a diverse subset per digit (farthest-point sampling)
    keep = {}
    for ch, vs in samples.items():
        sel = [0]
        while len(sel) < min(KEEP_PER_DIGIT, len(vs)):
            d = [min(np.sum((vs[j] - vs[k]) ** 2) for k in sel) for j in range(len(vs))]
            sel.append(int(np.argmax(d)))
        keep[ch] = [''.join(str(min(9, int(round(x * 9)))) for x in vs[j]) for j in sel]
    with open(os.path.join(root, 'js', 'data', 'digit-templates.js'), 'w') as f:
        f.write('// Generated by tools/build_digit_templates.py. Do not edit by hand.\n')
        f.write(f'// Each sample is a {CW}x{CH} grid, one char 0-9 per pixel (brightness).\n')
        f.write('export const DIGIT_TEMPLATES = ' + json.dumps(keep, indent=0) + ';\n')
    # small fixture for tests: 14 cards covering most digits
    pick = list(crops)[::3][:16]
    fx = {n: {'power': crops[n][1], 'gray': base64.b64encode(crops[n][0].astype('uint8').tobytes()).decode()} for n in pick}
    json.dump(fx, open(os.path.join(root, 'test', 'fixtures', 'power-crops.json'), 'w'))
    print({k: len(v) for k, v in sorted(keep.items())}, 'fixture cards:', len(pick))


if __name__ == '__main__':
    main()
